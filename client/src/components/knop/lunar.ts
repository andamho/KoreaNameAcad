export function getLunarDate(y: number, m: number, d: number): string {
  const ts = new Date(y, m - 1, d).getTime();
  let idx = -1;
  for (let i = 0; i < LMT.length - 1; i++) {
    const s = new Date(LMT[i][0], LMT[i][1]-1, LMT[i][2]).getTime();
    const e = new Date(LMT[i+1][0], LMT[i+1][1]-1, LMT[i+1][2]).getTime();
    if (ts >= s && ts < e) { idx = i; break; }
  }
  if (idx === -1) {
    // 범위 밖: 근사치
    const ref = new Date(2026, 3, 17).getTime(); // 음력 2026.3.1 = 4/17
    const diff = Math.round((ts - ref) / 86400000);
    const lm = ((Math.floor(diff / 29.53) + 2) % 12) + 1;
    const ld = Math.abs(diff % 30) + 1;
    return `${lm}.${Math.min(ld, 30)}`;
  }
  const r = LMT[idx];
  const startTs = new Date(r[0], r[1]-1, r[2]).getTime();
  const lDay = Math.floor((ts - startTs) / 86400000) + 1;
  return `${r[5] ? '윤' : ''}${r[4]}.${lDay}`;
}
